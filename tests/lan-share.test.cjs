const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const {execFileSync} = require('node:child_process');
const root = path.resolve(__dirname,'..');
const csc = path.join(process.env.WINDIR,'Microsoft.NET','Framework64','v4.0.30319','csc.exe');
const out = path.join(fs.mkdtempSync(path.join(os.tmpdir(),'selective-lan-tests-')),'LanShareTests.exe');
execFileSync(csc,['/nologo','/target:exe','/main:LanShareTests','/reference:Microsoft.CSharp.dll','/reference:System.ServiceProcess.dll',`/out:${out}`,path.join(root,'helper/source/SelectiveAccessLanShare.cs'),path.join(root,'helper/source/SelectiveAccessGateway.cs'),path.join(__dirname,'LanShareTests.cs')],{stdio:'inherit',windowsHide:true});
execFileSync(out,[],{stdio:'inherit',windowsHide:true,timeout:15000});
const src=fs.readFileSync(path.join(root,'helper/source/SelectiveAccessLanShare.cs'),'utf8');
const installer=fs.readFileSync(path.join(root,'helper/install.cmd'),'utf8');
const uninstaller=fs.readFileSync(path.join(root,'helper/uninstall.cmd'),'utf8');
const hash=crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'helper/bin/SelectiveAccessLanShare.exe'))).digest('hex').toUpperCase();
assert.equal(installer.match(/SHARE_HASH=([A-F0-9]{64})/)?.[1],hash);
assert.match(installer,/"%TARGET_SHARE%" --off/);
assert.match(uninstaller,/SelectiveAccessLanShare\.exe" --off/);
assert.ok(installer.indexOf('icacls.exe') < installer.indexOf('"%TARGET_SHARE%" --off'),'secure ACL before execution');
assert.match(src,/CurrentProfileTypes != 2/);
assert.match(src,/FirewallEnabled\[2\]/);
assert.match(src,/ExcludedInterfaces\[2\]/);
assert.match(src,/new TcpListener\(Selected.Address, Port\)/);
assert.match(src,/PermittedPeer\(\(\(IPEndPoint\)client.Client.RemoteEndPoint\).Address, Selected\)/);
assert.match(src,/Timer monitor[\s\S]*BindingPresent\(Selected\)\) Stop.Cancel\(\)/);
assert.doesNotMatch(src,/IPAddress.Any|profile=any|remoteip=any|advfirewall reset|state off/);
console.log('LAN firewall and binding guards passed');
